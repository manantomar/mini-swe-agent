#!/usr/bin/env python3
"""Score agent trajectories with per-token logprobs using a local model.

Takes trajectory files generated by mini-swe-agent and computes per-token
log-probabilities for each assistant response using a local model forward pass.

Usage:
    python rl/score_logprobs.py \
        --model Qwen/Qwen3-8B \
        --traces-dir /data/manantomar/swe-bench-docker/qwen3-30b-50new \
        --output-dir /data/manantomar/swe-bench-docker/qwen3-30b-50new-scored \
        --batch-size 1

Outputs one JSON file per trajectory with logprobs attached to each assistant step.
"""

import argparse
import json
import logging
from pathlib import Path

import torch
from transformers import AutoModelForCausalLM, AutoTokenizer
from tqdm import tqdm

logging.basicConfig(level=logging.INFO, format="%(asctime)s %(message)s")
logger = logging.getLogger(__name__)

BASH_TOOL = {
    "type": "function",
    "function": {
        "name": "bash",
        "parameters": {
            "type": "object",
            "properties": {"command": {"type": "string", "description": "Bash command to run"}},
            "required": ["command"],
        },
    },
}


def load_trajectory(path: Path) -> dict:
    return json.loads(path.read_text())


def build_chat_messages(messages: list[dict]) -> list[dict]:
    """Convert trajectory messages to the format expected by apply_chat_template.

    Strips 'extra' fields and normalizes tool_calls format.
    """
    cleaned = []
    for m in messages:
        msg = {"role": m["role"]}
        if m.get("content"):
            msg["content"] = m["content"]
        if m.get("tool_calls"):
            msg["tool_calls"] = [
                {
                    "id": tc.get("id", ""),
                    "type": "function",
                    "function": {
                        "name": tc["function"]["name"],
                        "arguments": tc["function"]["arguments"],
                    },
                }
                for tc in m["tool_calls"]
            ]
        if m.get("tool_call_id"):
            msg["tool_call_id"] = m["tool_call_id"]
        cleaned.append(msg)
    return cleaned


def compute_step_logprobs(
    model,
    tokenizer,
    messages_up_to_step: list[dict],
    device: str = "cuda",
) -> dict:
    """Compute logprobs for the last assistant message given the conversation history.

    Returns dict with:
        - token_ids: list of token IDs for the assistant response
        - logprobs: list of log-probabilities for each token
        - tokens: list of decoded token strings
    """
    # Tokenize full conversation (prompt + response)
    full_text = tokenizer.apply_chat_template(
        messages_up_to_step, tools=[BASH_TOOL], tokenize=False, add_generation_prompt=False
    )
    full_ids = tokenizer.encode(full_text, add_special_tokens=False)

    # Tokenize conversation without the last assistant message (prompt only)
    prompt_messages = messages_up_to_step[:-1]
    prompt_text = tokenizer.apply_chat_template(
        prompt_messages, tools=[BASH_TOOL], tokenize=False, add_generation_prompt=True
    )
    prompt_ids = tokenizer.encode(prompt_text, add_special_tokens=False)

    # The response tokens are the difference
    response_start = len(prompt_ids)
    if response_start >= len(full_ids):
        return {"token_ids": [], "logprobs": [], "tokens": []}

    # Forward pass
    input_ids = torch.tensor([full_ids], device=device)
    with torch.no_grad():
        outputs = model(input_ids)
        # logits shape: [1, seq_len, vocab_size]
        logits = outputs.logits[0]  # [seq_len, vocab_size]

    # Compute log-probabilities for the response tokens
    # For token at position t, the logit at position t-1 predicts it
    log_probs = torch.log_softmax(logits, dim=-1)

    response_token_ids = full_ids[response_start:]
    response_logprobs = []
    for i, token_id in enumerate(response_token_ids):
        pos = response_start - 1 + i  # logit position that predicts this token
        if pos < 0 or pos >= log_probs.shape[0]:
            response_logprobs.append(0.0)
        else:
            response_logprobs.append(log_probs[pos, token_id].item())

    response_tokens = [tokenizer.decode([tid]) for tid in response_token_ids]

    return {
        "token_ids": response_token_ids,
        "logprobs": response_logprobs,
        "tokens": response_tokens,
    }


def score_trajectory(
    model,
    tokenizer,
    trajectory: dict,
    device: str = "cuda",
) -> list[dict]:
    """Score all assistant steps in a trajectory with logprobs.

    Returns a list of scored steps, one per assistant message.
    """
    messages = trajectory["messages"]
    cleaned = build_chat_messages(messages)

    scored_steps = []
    for i, msg in enumerate(cleaned):
        if msg["role"] != "assistant":
            continue

        # Build conversation up to and including this assistant message
        messages_up_to = cleaned[: i + 1]

        try:
            step_logprobs = compute_step_logprobs(model, tokenizer, messages_up_to, device)
            scored_steps.append(
                {
                    "step_index": i,
                    "n_tokens": len(step_logprobs["token_ids"]),
                    "sum_logprob": sum(step_logprobs["logprobs"]),
                    "mean_logprob": (
                        sum(step_logprobs["logprobs"]) / len(step_logprobs["logprobs"])
                        if step_logprobs["logprobs"]
                        else 0.0
                    ),
                    "token_ids": step_logprobs["token_ids"],
                    "logprobs": step_logprobs["logprobs"],
                    "tokens": step_logprobs["tokens"],
                }
            )
        except Exception as e:
            logger.warning(f"Failed to score step {i}: {e}")
            scored_steps.append(
                {
                    "step_index": i,
                    "error": str(e),
                    "n_tokens": 0,
                    "sum_logprob": 0.0,
                    "mean_logprob": 0.0,
                    "token_ids": [],
                    "logprobs": [],
                    "tokens": [],
                }
            )

    return scored_steps


def main():
    parser = argparse.ArgumentParser(description="Score trajectories with logprobs")
    parser.add_argument("--model", type=str, default="Qwen/Qwen3-8B", help="HuggingFace model name")
    parser.add_argument("--traces-dir", type=str, required=True, help="Directory with trajectory files")
    parser.add_argument("--output-dir", type=str, required=True, help="Output directory for scored trajectories")
    parser.add_argument("--device", type=str, default="cuda:0", help="Device to use")
    parser.add_argument("--max-seq-len", type=int, default=16384, help="Max sequence length to score")
    parser.add_argument("--dtype", type=str, default="bfloat16", choices=["float16", "bfloat16", "float32"])
    args = parser.parse_args()

    output_dir = Path(args.output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)

    # Find all trajectory files
    traces_dir = Path(args.traces_dir)
    traj_files = sorted(traces_dir.glob("*/*.traj.json"))
    logger.info(f"Found {len(traj_files)} trajectory files in {traces_dir}")

    if not traj_files:
        logger.error("No trajectory files found!")
        return

    # Load model and tokenizer
    logger.info(f"Loading model {args.model} on {args.device} with {args.dtype}...")
    dtype = getattr(torch, args.dtype)
    tokenizer = AutoTokenizer.from_pretrained(args.model, trust_remote_code=True)
    model = AutoModelForCausalLM.from_pretrained(
        args.model,
        torch_dtype=dtype,
        device_map=args.device,
        trust_remote_code=True,
    )
    model.eval()
    logger.info("Model loaded.")

    # Score each trajectory
    results_summary = []
    for traj_file in tqdm(traj_files, desc="Scoring trajectories"):
        instance_id = traj_file.parent.name
        output_file = output_dir / f"{instance_id}.scored.json"

        if output_file.exists():
            logger.info(f"Skipping {instance_id} (already scored)")
            continue

        trajectory = load_trajectory(traj_file)
        info = trajectory.get("info", {})
        exit_status = info.get("exit_status", "unknown")

        # Check sequence length
        messages = trajectory["messages"]
        cleaned = build_chat_messages(messages)
        try:
            full_text = tokenizer.apply_chat_template(
                cleaned, tools=[BASH_TOOL], tokenize=False, add_generation_prompt=False
            )
            n_tokens = len(tokenizer.encode(full_text, add_special_tokens=False))
        except Exception:
            n_tokens = 0

        if n_tokens > args.max_seq_len:
            logger.warning(f"Skipping {instance_id}: {n_tokens} tokens exceeds max {args.max_seq_len}")
            scored = {"instance_id": instance_id, "skipped": True, "reason": f"too_long ({n_tokens} tokens)"}
        else:
            logger.info(f"Scoring {instance_id} ({n_tokens} tokens, {exit_status})...")
            scored_steps = score_trajectory(model, tokenizer, trajectory, device=args.device)
            scored = {
                "instance_id": instance_id,
                "exit_status": exit_status,
                "n_messages": len(messages),
                "n_tokens_total": n_tokens,
                "n_steps_scored": len(scored_steps),
                "total_sum_logprob": sum(s["sum_logprob"] for s in scored_steps),
                "steps": scored_steps,
            }

        output_file.write_text(json.dumps(scored, indent=2))
        results_summary.append(
            {
                "instance_id": instance_id,
                "exit_status": exit_status if not scored.get("skipped") else "skipped",
                "n_steps": scored.get("n_steps_scored", 0),
                "n_tokens": scored.get("n_tokens_total", 0),
            }
        )

    # Write summary
    summary_file = output_dir / "scoring_summary.json"
    summary_file.write_text(json.dumps(results_summary, indent=2))
    logger.info(f"Done! Scored {len(results_summary)} trajectories. Summary: {summary_file}")


if __name__ == "__main__":
    main()
